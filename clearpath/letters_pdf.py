"""
PDF rendering and email delivery for ClearPath clearance letters.

The PDF renderer wraps the letter's HTML body in a clinical-letter template
with letterhead, recipient/sender block, subject line, and a footer disclaimer
that the letter is a draft for clinician review. PDFs are generated on demand
from the persisted letter — no PDF is stored at rest.

The email sender supports two backends:
  - SMTP via stdlib smtplib (configured via env vars)
  - "captured" fallback that just logs the would-be send (default when no
    SMTP config is present, so the demo never crashes for missing credentials)
"""

from __future__ import annotations

import io
import os
import smtplib
import ssl
from dataclasses import dataclass
from datetime import datetime, timezone
from email.message import EmailMessage
from typing import Any

from xhtml2pdf import pisa


