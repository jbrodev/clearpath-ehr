@dataclass
class LetterMeta:
    to: str
    sender: str
    subject: str
    date: str | None = None


def render_letter_pdf(meta: LetterMeta, body_html: str) -> bytes:
    """Render a letter to PDF bytes using xhtml2pdf."""
    now = datetime.now(timezone.utc)
    date_str = meta.date or now.strftime("%B %d, %Y")
    html = _PDF_TEMPLATE.format(
        facility_name=_html_escape(_LETTERHEAD["facility_name"]),
        facility_address=_html_escape(_LETTERHEAD["facility_address"]),
        facility_phone=_html_escape(_LETTERHEAD["facility_phone"]),
        facility_fax=_html_escape(_LETTERHEAD["facility_fax"]),
        date=_html_escape(date_str),
        to=_html_escape(meta.to),
        from_=_html_escape(meta.sender),
        subject=_html_escape(meta.subject),
        body_html=body_html or "<p><em>(empty letter body)</em></p>",
        generated_at=_html_escape(now.strftime("%Y-%m-%d %H:%M UTC")),
    )

    buf = io.BytesIO()
    result = pisa.CreatePDF(src=html, dest=buf)
    if result.err:
        raise RuntimeError(f"PDF rendering failed: {result.err}")
    return buf.getvalue()


def _html_escape(s: str) -> str:
    return (
        s.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


# --- Email delivery ---------------------------------------------------------


@dataclass
class EmailDeliveryResult:
    sent: bool
    via: str
    detail: str | None = None


def send_letter_email(
    *,
    to_email: str,
    to_name: str | None,
    subject: str,
    body_text: str,
    pdf_bytes: bytes,
    pdf_filename: str,
) -> EmailDeliveryResult:
    """Send the letter PDF as an email attachment.

    Configuration via env vars:
      CLEARPATH_SMTP_HOST, CLEARPATH_SMTP_PORT (default 587),
      CLEARPATH_SMTP_USER, CLEARPATH_SMTP_PASS, CLEARPATH_FROM_EMAIL.

    When SMTP isn't configured, the call records a "captured" delivery — the
    UI shows the user the message would have gone out, no exception. This
    keeps the demo running without credentials while still letting prod
    deployments turn on real sending with three env vars.
    """
    host = os.environ.get("CLEARPATH_SMTP_HOST")
    user = os.environ.get("CLEARPATH_SMTP_USER")
    password = os.environ.get("CLEARPATH_SMTP_PASS")
    from_email = os.environ.get("CLEARPATH_FROM_EMAIL")
    port = int(os.environ.get("CLEARPATH_SMTP_PORT", "587"))

    if not (host and user and password and from_email):
        return EmailDeliveryResult(
            sent=False,
            via="captured",
            detail=(
                "SMTP is not configured (CLEARPATH_SMTP_HOST / CLEARPATH_SMTP_USER / "
                "CLEARPATH_SMTP_PASS / CLEARPATH_FROM_EMAIL). The PDF was generated but "
                "no email was transmitted. Configure these env vars to enable real sending."
            ),
        )

    msg = EmailMessage()
    msg["From"] = from_email
    msg["To"] = f"{to_name} <{to_email}>" if to_name else to_email
    msg["Subject"] = subject
    msg.set_content(body_text or "Please see the attached PDF for the clearance letter.")
    msg.add_attachment(
        pdf_bytes,
        maintype="application",
        subtype="pdf",
        filename=pdf_filename,
    )

    try:
        context = ssl.create_default_context()
        with smtplib.SMTP(host, port, timeout=30) as smtp:
            smtp.ehlo()
            smtp.starttls(context=context)
            smtp.ehlo()
            smtp.login(user, password)
            smtp.send_message(msg)
        return EmailDeliveryResult(sent=True, via="smtp", detail=f"Sent via {host}:{port}")
    except Exception as e:
        return EmailDeliveryResult(
            sent=False,
            via="smtp",
            detail=f"SMTP send failed: {type(e).__name__}: {e}",
        )


# --- Helpers used by the API endpoints --------------------------------------


def find_letter_in_workflow(workflow: dict[str, Any], letter_id: str) -> dict[str, Any] | None:
    for letter in workflow.get("letters", []) or []:
        if letter.get("id") == letter_id:
            return letter
    return None


def letter_meta_from(letter: dict[str, Any], default_sender: str = "Clinical Office") -> LetterMeta:
    return LetterMeta(
        to=letter.get("to") or "Recipient",
        sender=letter.get("from") or default_sender,
        subject=letter.get("subject") or "Pre-Operative Clearance",
        date=letter.get("sentAt"),
    )


def safe_pdf_filename(subject: str) -> str:
    base = subject or "letter"
    cleaned = "".join(c if c.isalnum() or c in (" ", "-", "_") else "_" for c in base)
    return cleaned.strip().replace(" ", "_")[:80] + ".pdf"
